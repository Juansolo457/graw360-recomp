#!/usr/bin/env python3
"""Compiles the Vulkan backend's own shaders (native/shaders/*.comp, ...) into SPIR-V headers
(native/shaders/bytecode/*.h) with glslc (the Vulkan SDK's, or one on PATH). The headers are
committed, so builds don't need glslc; run this after changing a shader.

    python tools/vulkan_shaders.py
"""
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'native', 'shaders')
OUT = os.path.join(SRC, 'bytecode')

# (source, header name, array name, defines)
SHADERS = [
    ('depth_resolve.comp', 'depth_resolve_1x', 'kDepthResolve1x', ['MSAA=0']),
    ('depth_resolve.comp', 'depth_resolve_msaa', 'kDepthResolveMsaa', ['MSAA=1']),
    ('color_resolve.comp', 'color_resolve_1x', 'kColorResolve1x', ['MSAA=0']),
    ('color_resolve.comp', 'color_resolve_msaa', 'kColorResolveMsaa', ['MSAA=1']),
]


def find_glslc():
    sdk = os.environ.get('VULKAN_SDK')
    if sdk:
        for name in ('Bin/glslc.exe', 'bin/glslc'):
            path = os.path.join(sdk, name)
            if os.path.isfile(path):
                return path
    return shutil.which('glslc')


def main():
    glslc = find_glslc()
    if not glslc:
        sys.exit('glslc not found (install the Vulkan SDK, or glslc on Linux)')
    os.makedirs(OUT, exist_ok=True)
    for source, header, array, defines in SHADERS:
        with tempfile.TemporaryDirectory() as tmp:
            spv = os.path.join(tmp, 'out.spv')
            cmd = [glslc, '--target-env=vulkan1.3', '-O', '-o', spv, os.path.join(SRC, source)]
            cmd += ['-D' + d for d in defines]
            subprocess.run(cmd, check=True)
            data = open(spv, 'rb').read()
        words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
        lines = [', '.join(f'0x{w:08X}' for w in words[i:i + 8]) + ','
                 for i in range(0, len(words), 8)]
        text = (f'// Generated by tools/vulkan_shaders.py from native/shaders/{source} '
                f'({" ".join("-D" + d for d in defines)}). Do not edit.\n'
                '#pragma once\n\n#include <cstdint>\n\n'
                f'inline constexpr uint32_t {array}[] = {{\n' +
                ''.join(f'    {l}\n' for l in lines) + '};\n')
        with open(os.path.join(OUT, header + '.h'), 'w', newline='\n') as f:
            f.write(text)
        print(f'{header}.h: {len(words)} words')


if __name__ == '__main__':
    main()
